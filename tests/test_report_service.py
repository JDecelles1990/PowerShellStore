def test_report_service_clipboard_and_file_export(qapp, tmp_path):
    """Verify clipboard sets both HTML and Plain Text, and file export creates UTF-8 HTML."""
    service = ReportService()
    result = RunResult(
        script_id=4,
        duration_ms=200,
        exit_code=0,
        status="pass",
        summary="Drive C: has 124 GB free space.",
        data=[{"Drive": "C:", "FreeGB": 124, "PercentFree": "25%"}],
        errors=[],
        raw_output="Drive C: 124 GB Free",
    )

    # 1. MIME Data Packaging (HTML + Plain text)
    mime = service.create_mime_data(
        script_title="Check Disk Space",
        result=result,
        script_category="System",
    )
    assert mime.hasHtml() is True
    assert mime.hasText() is True
    assert "Check Disk Space" in mime.html()
    assert "Drive C: has 124 GB free space." in mime.text()

    # 2. Clipboard Copy Operation
    success = service.copy_ticket_report_to_clipboard(
        script_title="Check Disk Space",
        result=result,
        script_category="System",
    )
    assert success is True

    # 3. File Export
    report_file = tmp_path / "test_report.html"
    saved_path = service.save_html_report(
        file_path=report_file,
        script_title="Check Disk Space",
        result=result,
        script_category="System",
    )
    assert saved_path.exists()
    content = saved_path.read_text(encoding="utf-8")
    assert "<!DOCTYPE html>" in content
    assert "Check Disk Space" in content
    assert "124" in content


def test_console_view_reporting_buttons(qapp):
    """Verify ConsoleView enables reporting buttons on result display and handles history clicks."""
    service = ReportService()
    view = ConsoleView(report_service=service)

    # Initially reporting buttons are disabled
    assert view.copy_report_btn.isEnabled() is False
    assert view.save_report_btn.isEnabled() is False

    # After displaying a result, buttons become active
    res = RunResult(
        script_id=10,
        duration_ms=300,
        exit_code=0,
        status="pass",
        summary="Uptime: 4 days 3 hours.",
        data=[{"Uptime": "4.12 days"}],
        errors=[],
        raw_output="4.12 days",
    )
    view.set_script_context("Get System Uptime", "System")
    view.display_run_result(res)

    assert view.copy_report_btn.isEnabled() is True
    assert view.save_report_btn.isEnabled() is True

    # Test clicking Copy Ticket Report button
    view._on_copy_report_clicked()
    assert view.copy_report_btn.text() == "✓ Report Copied!"

    # Test history double-click enables reporting buttons as well
    hist_rec = RunHistoryRecord(
        script_id=10,
        duration_ms=250,
        exit_code=0,
        status="pass",
        summary="Historical uptime check",
        parameters_json="{}",
        raw_output="4.10 days",
        json_payload='{"status": "pass", "summary": "Historical uptime check", "data": [{"Uptime": "4.10 days"}], "errors": []}',
        executed_at="2026-11-10 10:00:00",
        id=1,
    )
    view.display_history([hist_rec])
    view._on_history_double_clicked(0, 0)

    assert view.copy_report_btn.isEnabled() is True
    assert view.save_report_btn.isEnabled() is True
    assert "Historical uptime check" in view.summary_box.text()
